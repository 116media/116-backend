using _116.Content.Domain.Enums;
using NpgsqlTypes;

namespace _116.Content.Infrastructure.Persistence.Projections;

/// <summary>
/// One searchable item, projected from its source aggregate. A single table holds every
/// content type, so a search is one query and the per-scope counts one aggregate, whatever
/// the type is. The source tables remain the record; this is a derived read model.
/// </summary>
public class SearchDocument
{
    /// <summary>
    /// The content type this document was projected from, and the discriminator a scope
    /// narrows on.
    /// </summary>
    public EnumCoreContentType Type { get; init; }

    /// <summary>
    /// The source aggregate's identifier.
    /// </summary>
    public Guid EntityId { get; init; }

    /// <summary>
    /// The URL slug of the item's detail page.
    /// </summary>
    public string Slug { get; set; } = string.Empty;

    /// <summary>
    /// Whether the public can reach the item: published for the editorial types, active for
    /// the ones with no editorial workflow. Hidden documents stay in the table so a
    /// republish costs an update rather than a reinsert.
    /// </summary>
    public bool IsVisible { get; set; }

    /// <summary>
    /// The highest-weighted text, matched at weight A.
    /// </summary>
    public string Title { get; set; } = string.Empty;

    /// <summary>
    /// The teaser text, matched at weight B, and the source of the display excerpt.
    /// </summary>
    public string Summary { get; set; } = string.Empty;

    /// <summary>
    /// Secondary terms such as SEO fields, matched at weight C.
    /// </summary>
    public string Keywords { get; set; } = string.Empty;

    /// <summary>
    /// The long-form text, matched at weight D.
    /// </summary>
    public string Body { get; set; } = string.Empty;

    /// <summary>
    /// The cover or thumbnail file, resolved to a URL on read.
    /// </summary>
    public Guid? ImageFileId { get; set; }

    /// <summary>
    /// The owning category, resolved to a name on read; null for a type that has none.
    /// </summary>
    public Guid? CategoryId { get; set; }

    /// <summary>
    /// When the item became public, or when it was created for a type that has no
    /// publication date. Orders a tie in relevance.
    /// </summary>
    public DateTimeOffset? PublishedAt { get; set; }

    /// <summary>
    /// The weighted search vector, generated by the database from the four text columns.
    /// </summary>
    public NpgsqlTsVector SearchVector { get; private set; } = null!;
}
